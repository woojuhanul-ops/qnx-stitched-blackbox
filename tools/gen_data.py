#!/usr/bin/env python3
"""Generate ledger_data.h / exam_data.h from the Stitched Ledger assets.
Source of truth: ~/workspace/kiroween/stitched-ledger/data/ledger.json + exam/exam.json
"""
import json, pathlib
root = pathlib.Path.home() / "workspace/kiroween/stitched-ledger"
led = json.loads((root/"data/ledger.json").read_text())
exam = json.loads((root/"exam/exam.json").read_text())

def cs(s):
    if s is None: return "NULL"
    return '"' + s.replace("\\","\\\\").replace('"','\\"').replace("\n","\\n") + '"'

out = []
out.append("/* GENERATED by gen_data.py from stitched-ledger data/ledger.json - do not edit */")
out.append("#ifndef LEDGER_DATA_H\n#define LEDGER_DATA_H\n#include \"blackbox.h\"")
out.append(f"#define BB_NUM_ROWS {len(led)}")
total_chars = sum(len(r["name"]) for r in led)
out.append(f"#define BB_NAME_TOTAL_CHARS {total_chars}")
out.append("static const bb_row_t BB_ROWS[BB_NUM_ROWS] = {")
for r in led:
    links = ", ".join(r["links"])
    out.append("  { %s, %s, %s, %s, %ld, %s, %s, %s }," % (
        cs(r["name"]), cs(r["type"]), cs(r["location"]), cs(r["role"]),
        int(r["quantity"]), cs(r["unit"]), cs(r["hazard"]), cs(links)))
out.append("};\n#endif")
pathlib.Path("ledger_data.h").write_text("\n".join(out)+"\n")

out = []
out.append("/* GENERATED by gen_data.py from stitched-ledger exam/exam.json - do not edit */")
out.append("#ifndef EXAM_DATA_H\n#define EXAM_DATA_H\n#include \"blackbox.h\"")
out.append(f"#define BB_NUM_EXAM {len(exam)}")
out.append("static const bb_exam_t BB_EXAM[BB_NUM_EXAM] = {")
for e in exam:
    st = 0 if e["expectedStatus"]=="ANSWER" else 1
    ev = e.get("expectedEvidence") or []
    evs = ", ".join("{ %d, %s }" % (x["row"], cs(x["col"])) for x in ev)
    out.append("  { %d, %s, %s, %d, %s, { %s }, %d }," % (
        e["id"], cs(e["type"]), cs(e["question"]), st, cs(e.get("expectedAnswer")), evs, len(ev)))
out.append("};\n#endif")
pathlib.Path("exam_data.h").write_text("\n".join(out)+"\n")
print("generated: rows=%d exam=%d name_chars=%d" % (len(led), len(exam), total_chars))
